"""Builds src/products.json from the store inventory (מלאי_חנות_3D.xlsx).
Usage: python scripts/build-products.py [path-to-xlsx]
Only rows with status 'מוכן למכירה' are published."""
import json, sys, pathlib
from openpyxl import load_workbook

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = sys.argv[1] if len(sys.argv) > 1 else ROOT / 'scripts' / 'inventory.xlsx'

# inventory category -> store category id
CAT_MAP = {
    'מטבח': 'kitchen',
    'קערות ומגשים': 'home', 'עיצוב ואגרטלים': 'home', 'שלטים ושונות': 'home',
    'אמבטיה': 'bath',
    'כניסה ומפתחות': 'entrance', 'מדפים ומתלים': 'entrance',
    'תכשיטים ואקססוריז': 'jewelry',
    "צעצועי פידג'ט": 'fidget',
    'דמויות מפרקיות': 'flexi',
}
COMMERCIAL_OK = {'CC0'}  # licenses that allow selling prints without buying anything

wb = load_workbook(src, data_only=True)
ws = wb['מלאי']
hdr = [c.value for c in ws[1]]
col = {h: i for i, h in enumerate(hdr)}
out = []
workshop = []  # admin-only data -> Supabase (never shipped to the store)
for r in ws.iter_rows(min_row=2, values_only=True):
    sku = r[col['מק"ט']]
    if not sku or r[col['סטטוס']] != 'מוכן למכירה':
        continue
    lic = r[col['רישיון (MakerWorld)']] or ''
    def num(h):
        try: return float(r[col[h]]) if h in col and r[col[h]] is not None else None
        except (TypeError, ValueError): return None
    workshop.append({
        'sku': sku,
        'makerworld_url': r[col['קישור MakerWorld']] if 'קישור MakerWorld' in col else None,
        'grams': num('משקל פילמנט (גרם)'),
        'print_hours': num('זמן הדפסה (שעות)'),
        'profile': r[col['פרופיל הדפסה נבחר']] if 'פרופיל הדפסה נבחר' in col else None,
        'plates': int(num('מס׳ פלטות')) if num('מס׳ פלטות') is not None else None,
    })
    out.append({
        'sku': sku,
        'name': r[col['שם המוצר']],
        'subcategory': r[col['קטגוריה']],
        'category': CAT_MAP.get(r[col['קטגוריה']], 'home'),
        'price': int(r[col['מחיר לצרכן כולל מע"מ (₪)']] or 0),
        'image': next((f'/assets/products/{sku}.{e}' for e in ('webp','jpg','jpeg','png')
                       if (ROOT / 'public' / 'assets' / 'products' / f'{sku}.{e}').exists()), None),
    })
dst = ROOT / 'src' / 'products.json'
dst.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding='utf-8')
print(f'{len(out)} products -> {dst}')

# ---- workshop data for the admin page (MakerWorld link, grams, print time) ----
def lit(v):
    if v is None: return 'null'
    if isinstance(v, (int, float)): return repr(round(v, 2))
    return "'" + str(v).replace("'", "''") + "'"
sql = ['-- Generated by scripts/build-products.py. Run in Supabase SQL editor (project noamaker) after inventory changes.',
       'insert into public.product_workshop (sku, makerworld_url, grams, print_hours, profile, plates) values']
sql.append(',\n'.join(f"({lit(w['sku'])}, {lit(w['makerworld_url'])}, {lit(w['grams'])}, {lit(w['print_hours'])}, {lit(w['profile'])}, {lit(w['plates'])})" for w in workshop))
sql.append('on conflict (sku) do update set makerworld_url = excluded.makerworld_url, grams = excluded.grams, print_hours = excluded.print_hours, profile = excluded.profile, plates = excluded.plates;')
wdst = ROOT / 'supabase' / 'workshop-data.sql'
wdst.parent.mkdir(exist_ok=True)
wdst.write_text('\n'.join(sql) + '\n', encoding='utf-8')
print(f'{len(workshop)} workshop rows -> {wdst}')
